import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { checkWorkspaceTransfer } from './v5-workspace-transfer.mjs';
import { checkV5Deadlines } from './v5-deadlines.mjs';
import { checkCaseDocuments } from './v5-documents-browser.mjs';
import { checkSavingsCenter } from './v5-savings-browser.mjs';
import { checkWorkspaceBackup } from './v5-workspace-backup.mjs';
const origin=process.env.VSETKO_ORIGIN??'http://127.0.0.1:4321';
const browser=await chromium.launch({headless:true});
try {
 const context=await browser.newContext({viewport:{width:390,height:844}});
 const page=await context.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 let personalRequests=0;
 page.on('request',req=>{if(new URL(req.url()).pathname.startsWith('/api/'))personalRequests++;});
 await page.goto(origin+'/moje-situacie/');
 await page.locator('#case-title').fill('Rodinné auto');
 await page.locator('#case-create button').click();
 await page.locator('#case-detail').waitFor({state:'visible'});
 await page.locator('.case-inputs summary').click();
 for(const [key,value] of Object.entries({purchasePrice:24000,downPayment:4000,annualRate:0,loanYears:4,monthlyIncome:2500,monthlyExpenses:1200,monthlyService:50,monthlyInsurance:40}))await page.locator('#case-'+key).fill(String(value));
 await page.locator('#case-values button[type=submit]').click();
 assert.match(await page.locator('#case-projection').innerText(),/416,67/);
 await page.locator('#case-steps input').first().check();
 await page.reload();
 assert.equal(await page.locator('#case-steps input').first().isChecked(),true);
 assert.equal(await page.locator('#case-purchasePrice').inputValue(),'24000');
 await page.locator('#case-kind').selectOption('home');await page.locator('#case-title').fill('Bývanie');await page.locator('#case-create button').click();
 assert.equal(await page.locator('#case-steps input').first().isChecked(),false);
 assert.equal(await page.locator('#case-purchasePrice').inputValue(),'');
 await page.getByRole('button',{name:'Rodinné auto · 1/8',exact:true}).click();
 assert.equal(await page.locator('#case-steps input').first().isChecked(),true);
 const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#case-export').click()]);assert.equal(download.suggestedFilename(),'moja-situacia.txt');
 await page.evaluate(()=>document.documentElement.dataset.theme='dark');
 await page.screenshot({path:'v5-workspace-mobile-dark.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'workspace mobile overflow');
 await page.goto(origin+'/navody/prepis-auta/');
 await page.locator('[data-report-step]').first().click();
 await page.locator('#report-detail').fill('Odkaz v tomto kroku neotvoril očakávanú stránku.');
 await page.locator('#content-report-form button[type=submit]').click();
 assert.match(await page.locator('#report-preview').inputValue(),/prepis-auta/);
 const [report]=await Promise.all([page.waitForEvent('download'),page.locator('#report-download').click()]);assert.ok(report.suggestedFilename().endsWith('.txt'));
 assert.equal(personalRequests,0,'case and report use no API');
 assert.deepEqual(errors,[]);
 await context.close();
 const blocked=await browser.newContext({viewport:{width:390,height:844}});
 await blocked.addInitScript(()=>{Object.defineProperty(window,'localStorage',{get(){throw new DOMException('blocked','SecurityError');}});});
 const bp=await blocked.newPage();await bp.goto(origin+'/moje-situacie/');await bp.locator('#case-create button').click();assert.equal(await bp.locator('#case-detail').isVisible(),true);assert.match(await bp.locator('#workspace-status').innerText(),/dočasné/);await blocked.close();
 console.log('PASS V5 saved cases, isolated progress, projection, reload, TXT export, local correction report and blocked-storage fallback');
 await checkWorkspaceTransfer(browser,origin);
 await checkV5Deadlines(browser,origin);
 await checkCaseDocuments(browser,origin);
 await checkSavingsCenter(browser,origin);
 await checkWorkspaceBackup(browser,origin);
} finally {await browser.close();}
